//! The bundle embedded in the binary (`ADR-89` option B): one version with the
//! engine, available offline. `bundle/` is laid out so it could later also be
//! published as a release asset without a second format: `instructions.md`, and
//! one directory per adapter holding `adapter.json`, `settings.fragment.json`
//! and `files/`, whose tree is installed at the same relative paths.
//!
//! An adapter is exactly the agent-specific part. Everything else in the engine
//! names no agent: adapters are found here by the name the directory carries,
//! and `urzua harness adapters` lists them.

use serde::Deserialize;

/// The agent-instructions block, written between markers into the file
/// `harness.instructions_file` names.
pub const INSTRUCTIONS: &str = include_str!("../../bundle/instructions.md");

/// One adapter directory of the bundle, embedded.
pub struct Adapter {
    pub name: &'static str,
    manifest: &'static str,
    pub settings_fragment: &'static str,
    /// Command templates, (file name under `commands/`, content): `draft.md` is
    /// rendered once per record type, every other file is installed as it is.
    pub commands: &'static [(&'static str, &'static str)],
    /// (path relative to the repository root, content).
    pub files: &'static [(&'static str, &'static str)],
}

// Every adapter this build embeds, generated by `build.rs` from the directories
// under `bundle/`.
include!(concat!(env!("OUT_DIR"), "/bundle_table.rs"));

#[derive(Debug, Deserialize)]
pub struct Requires {
    /// Interpreters the adapter's translator runs under.
    pub interpreters: Vec<String>,
    /// Environment variables the agent sets for its hook commands.
    pub env: Vec<String>,
}

/// `adapter.json`.
#[derive(Debug, Deserialize)]
pub struct Manifest {
    pub name: String,
    pub description: String,
    /// The guardrails this adapter can wire. A guardrail the repository turns on
    /// that is not listed is reported, never skipped.
    pub provides: Vec<String>,
    /// The agent's project settings file the hook entries are merged into.
    pub settings_file: String,
    /// Where the agent looks for slash commands. Absent: this adapter installs none.
    #[serde(default)]
    pub commands_dir: Option<String>,
    pub requires: Requires,
}

impl Adapter {
    pub fn manifest(&self) -> Manifest {
        serde_json::from_str(self.manifest).unwrap_or_else(|e| {
            panic!("the embedded adapter.json of {} is invalid: {e}", self.name)
        })
    }
}

pub fn adapter(name: &str) -> Option<&'static Adapter> {
    ADAPTERS.iter().find(|a| a.name == name)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::{Path, PathBuf};

    fn bundle_dir() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("bundle")
    }

    fn files_under(dir: &Path, base: &Path, out: &mut Vec<String>) {
        for entry in std::fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                files_under(&path, base, out);
            } else {
                out.push(
                    path.strip_prefix(base)
                        .unwrap()
                        .to_string_lossy()
                        .to_string(),
                );
            }
        }
    }

    /// The table is generated from the directory, and a directory is named by
    /// the adapter its manifest declares.
    #[test]
    fn every_adapter_directory_and_file_in_the_bundle_is_embedded() {
        let mut dirs: Vec<String> = std::fs::read_dir(bundle_dir())
            .unwrap()
            .map(|e| e.unwrap().path())
            .filter(|p| p.is_dir())
            .map(|p| p.file_name().unwrap().to_string_lossy().to_string())
            .collect();
        dirs.sort();
        let embedded: Vec<&str> = ADAPTERS.iter().map(|a| a.name).collect();
        assert_eq!(dirs, embedded);
        for a in ADAPTERS {
            let root = bundle_dir().join(a.name);
            assert_eq!(a.manifest().name, a.name);
            let mut on_disk = Vec::new();
            files_under(&root.join("files"), &root.join("files"), &mut on_disk);
            on_disk.sort();
            let table: Vec<String> = a.files.iter().map(|(p, _)| p.to_string()).collect();
            assert_eq!(on_disk, table, "{}", a.name);
            for (path, content) in a.files {
                assert_eq!(
                    std::fs::read_to_string(root.join("files").join(path)).unwrap(),
                    *content
                );
            }
        }
    }

    #[test]
    fn an_adapter_provides_only_guardrails_the_engine_knows() {
        for a in ADAPTERS {
            for g in a.manifest().provides {
                assert!(urzua_core::harness::guardrail_info(&g).is_some(), "{g}");
            }
        }
    }
}
